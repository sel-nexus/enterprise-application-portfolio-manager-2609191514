import { expect, test } from '@playwright/test';

test('administrator creates, edits, retires and deletes an application', async ({ page }) => {
  const email = process.env.E2E_EMAIL;
  const password = process.env.E2E_NEW_PASSWORD;
  if (!email || !password) throw new Error('Set E2E_EMAIL and E2E_NEW_PASSWORD for an existing administrator.');
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const name = `Application E2E ${Date.now()}`;
  const portfolio = `Application portfolio ${Date.now()}`;
  await page.goto('/');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await page.getByRole('button', { name: 'New portfolio' }).click();
  await page.getByLabel('Name', { exact: true }).fill(portfolio);
  await page.getByLabel('Owner', { exact: true }).fill('Owner');
  await page.getByLabel('Product area', { exact: true }).fill('Finance');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Portfolio saved.')).toBeVisible();
  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  await page.getByRole('button', { name: 'New application' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByRole('dialog').getByLabel('Portfolio', { exact: true }).selectOption({ label: portfolio });
  await page.getByLabel('Business owner').fill('Alex');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(page.getByText('Application saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Edit details' }).click();
  await page.getByLabel('Business owner').fill('Jordan');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Jordan')).toBeVisible();
  await page.getByRole('button', { name: 'Change lifecycle' }).click();
  await page.getByRole('radio', { name: /Retired/ }).check();
  await page.getByRole('dialog').getByRole('button', { name: 'Save' }).click();
  await expect(page.getByText('Lifecycle changed.')).toBeVisible();
  await page.getByRole('link', { name: '← Applications' }).click();
  await page.getByLabel('Search name or business owner').fill(name);
  await expect(page.getByRole('link', { name, exact: true })).toHaveCount(0);
  await page.getByLabel('Lifecycle').selectOption('Retired');
  await page.getByRole('link', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click();
  await expect(page.getByRole('heading', { name: 'Applications', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
