"""Manage only the MongoDB database owned by this Playwright run.

The run ID and ownership token are generated by the Playwright config. A killed
runner, forced process termination, machine crash, or MongoDB outage can prevent
cleanup. The launcher prints the database name so an operator can investigate
and manually remove that specific test database after confirming ownership.
"""
import os
import re
import sys

from pymongo import MongoClient


def owned_database(client: MongoClient):
    """Verify both the generated name and the run's private ownership marker."""
    run_id = os.environ.get('E2E_RUN_ID', '')
    token = os.environ.get('E2E_DB_TOKEN', '')
    if not re.fullmatch(r'[0-9a-f]{32}', run_id) or not re.fullmatch(r'[0-9a-f]{64}', token):
        raise RuntimeError('Missing or invalid E2E database ownership information.')
    name = 'portfolio_e2e_' + run_id
    db = client[name]
    if db['_e2e_owner'].find_one({'_id': 'owner', 'token': token}) is None:
        raise RuntimeError(f'Refusing to modify {name}: ownership marker not found.')
    return db


def manage(action: str) -> None:
    """Checkpoint, restore, or remove the verified run database."""
    uri = os.environ.get('MONGODB_TEST_URI', 'mongodb://127.0.0.1:27017')
    with MongoClient(uri, serverSelectionTimeoutMS=5000) as client:
        db = owned_database(client)
        if action == 'drop':
            name = db.name
            client.drop_database(name)
            print(f'Dropped Playwright test database: {name}', flush=True)
        elif action == 'checkpoint':
            snapshot = db['_e2e_snapshot']
            if snapshot.find_one({'_id': 'ready'}):
                raise RuntimeError('E2E snapshot already exists.')
            for name in db.list_collection_names():
                if not name.startswith('_e2e_'):
                    for document in db[name].find():
                        snapshot.insert_one({'collection': name, 'document': document})
            snapshot.insert_one({'_id': 'ready'})
        elif action == 'reset':
            snapshot = db['_e2e_snapshot']
            if not snapshot.find_one({'_id': 'ready'}):
                raise RuntimeError('E2E snapshot is incomplete; refusing to reset.')
            entries = list(snapshot.find({'collection': {'$exists': True}}))
            names = {entry['collection'] for entry in entries}
            names.update(name for name in db.list_collection_names() if not name.startswith('_e2e_'))
            failures = []
            for name in sorted(names):
                try:
                    db[name].delete_many({})
                    documents = [entry['document'] for entry in entries if entry['collection'] == name]
                    if documents:
                        db[name].insert_many(documents)
                except Exception as exc:
                    failures.append(f'{name}: {exc}')
            if failures:
                raise RuntimeError('E2E reset failed: ' + '; '.join(failures))
        else:
            raise ValueError('Expected checkpoint, reset, or drop.')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Expected checkpoint, reset, or drop.')
    manage(sys.argv[1])
