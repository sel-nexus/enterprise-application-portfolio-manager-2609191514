import { expect, test } from './fixtures';
import { readFile } from 'node:fs/promises';

test('role restrictions, interval, filtered audit and CSV persist', async ({ page, request, admin }) => {
  const { email, password } = admin;
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const login = await request.post('/api/v1/accounts/login', { data: { email, password } });
  expect(login.status()).toBe(200);
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` };
  const rolesResponse = await request.get('/api/v1/admin/roles', { headers });
  expect(rolesResponse.status()).toBe(200);
  const originalRole = (await rolesResponse.json()).find((role: { name: string }) => role.name === 'read_only');
  expect(originalRole).toBeTruthy();
  const settingsResponse = await request.get('/api/v1/admin/settings', { headers });
  expect(settingsResponse.status()).toBe(200);
  const originalDays: number = (await settingsResponse.json()).days;
  const changedDays = originalDays === 120 ? 121 : 120;
  try {
  const prepared = await request.put('/api/v1/admin/roles/read_only', { headers, data: { description: originalRole.description, permissions: { ...originalRole.permissions, view: true } } });
  expect(prepared.status()).toBe(200);
  await page.goto('/');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  const role = page.getByRole('row').filter({ hasText: 'read only' });
  await role.getByRole('button', { name: 'Edit permissions' }).click();
  const dialog = page.getByRole('dialog');
  const description = `Restricted role ${Date.now()}`;
  await dialog.getByLabel('Description').fill(description);
  await expect(dialog.getByLabel('export')).toBeDisabled();
  await dialog.getByLabel('view').uncheck();
  const roleSaved = page.waitForResponse(r => r.url().endsWith('/api/v1/admin/roles/read_only') && r.request().method() === 'PUT');
  await dialog.getByRole('button', { name: 'Save' }).click();
  expect((await roleSaved).status()).toBe(200);
  await expect(role).toContainText(description);
  await role.getByRole('button', { name: 'Edit permissions' }).click();
  await expect(dialog.getByLabel('view')).not.toBeChecked();
  await dialog.getByLabel('view').check();
  await dialog.getByRole('button', { name: 'Save' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const days = page.getByLabel('Days');
  await expect(days).toHaveValue(String(originalDays));
  await days.fill(String(changedDays));
  const saved = page.waitForResponse(r => r.url().endsWith('/api/v1/reviews/interval') && r.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save interval' }).click();
  expect((await saved).status()).toBe(200);
  await expect(page.getByText('Review interval saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(days).toHaveValue(String(changedDays));
  await page.getByRole('button', { name: 'Audit', exact: true }).click();
  await page.getByLabel('Person').fill(admin.name);
  await page.getByLabel('Action').fill('permission_change');
  const today = new Date().toISOString().slice(0, 10);
  await page.getByLabel('From').fill(today);
  await page.getByLabel('To').fill(today);
  const filtered = page.waitForResponse(r => r.url().includes('/api/v1/admin/audit?') && r.url().includes('permission_change'));
  await page.getByRole('button', { name: 'Filter' }).click();
  const response = await filtered;
  expect(response.ok()).toBeTruthy();
  const data = await response.json();
  expect(data.total).toBeGreaterThan(0);
  expect(data.items.every((item: { who: string; action: string }) => item.who === admin.name && item.action === 'permission_change')).toBeTruthy();
  await expect(page.getByRole('row').filter({ hasText: 'Changed permissions for read_only' }).first()).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toBe('audit.csv');
  const path = await download.path();
  expect(path).toBeTruthy();
  const csv = await readFile(path!, 'utf8');
  expect(csv).toContain('Changed permissions for read_only');
  expect(csv).toContain('permission_change');
  expect(errors).toEqual([]);
  } finally {
    const roleRestored = await request.put('/api/v1/admin/roles/read_only', { headers, data: { description: originalRole.description, permissions: originalRole.permissions } });
    const intervalRestored = await request.put('/api/v1/reviews/interval', { headers, data: { days: originalDays } });
    expect(roleRestored.status(), 'restore role settings').toBe(200);
    expect(intervalRestored.status(), 'restore review interval').toBe(200);
  }
});
