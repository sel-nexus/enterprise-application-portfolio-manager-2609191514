import { expect, test } from './fixtures';
import { randomUUID } from 'node:crypto';

test('restricted engineer signs in without mutation or export controls and direct API calls are refused', async ({ page, request, admin }) => {
  test.setTimeout(90_000);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const login = await request.post('/api/v1/accounts/login', { data: { email: admin.email, password: admin.password } });
  expect(login.status()).toBe(200);
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` };
  const roles = await request.get('/api/v1/admin/roles', { headers });
  expect(roles.status()).toBe(200);
  const original = (await roles.json()).find((role: { name: string }) => role.name === 'engineer');
  expect(original).toBeTruthy();
  const id = randomUUID();
  const name = `00 Restricted app ${id}`, email = `restricted-${id}@example.com`;
  let portfolioId = '', applicationId = '', userId = '';
  try {
    const portfolio = await request.post('/api/v1/portfolios', { headers, data: { name: `00 Restricted portfolio ${id}`, owner: 'Owner', product_area: 'Finance' } });
    expect(portfolio.status()).toBe(201);
    portfolioId = (await portfolio.json()).id;
    const application = await request.post('/api/v1/applications', { headers, data: { name, portfolio_id: portfolioId, tier: 1 } });
    expect(application.status()).toBe(201);
    applicationId = (await application.json()).id;
    const user = await request.post('/api/v1/admin/users', { headers, data: { name: `Restricted engineer ${id}`, email, role: 'engineer', portfolio_ids: [portfolioId], temporary_password: admin.temporary } });
    expect(user.status()).toBe(201);
    userId = (await user.json()).id;
    const setupLogin = await request.post('/api/v1/accounts/login', { data: { email, password: admin.temporary } });
    expect(setupLogin.status()).toBe(200);
    const setup = await setupLogin.json();
    expect(setup.must_change_password).toBe(true);
    const passwordChange = await request.put('/api/v1/accounts/password', { headers: { Authorization: `Bearer ${setup.access_token}` }, data: { current_password: admin.temporary, new_password: admin.password, confirm_password: admin.password } });
    expect(passwordChange.status()).toBe(200);
    const prepared = await request.put('/api/v1/admin/roles/engineer', { headers, data: { description: original.description, permissions: { ...original.permissions, view: true, create: true, edit: true, export: true } } });
    expect(prepared.status()).toBe(200);

    await page.goto('/');
    await page.getByLabel('Email').fill(admin.email);
    await page.getByLabel('Password', { exact: true }).fill(admin.password);
    await page.getByRole('button', { name: 'Sign in' }).click();
    await page.getByRole('link', { name: 'Administration' }).click();
    await page.getByRole('button', { name: 'Roles', exact: true }).click();
    await page.getByRole('row').filter({ hasText: 'engineer' }).getByRole('button', { name: 'Edit permissions' }).click();
    const dialog = page.getByRole('dialog');
    for (const action of ['create', 'edit', 'export']) await dialog.getByLabel(action, { exact: true }).uncheck();
    const saved = page.waitForResponse(r => r.url().endsWith('/api/v1/admin/roles/engineer') && r.request().method() === 'PUT');
    await dialog.getByRole('button', { name: 'Save' }).click();
    expect((await saved).status()).toBe(200);
    await expect(dialog).toHaveCount(0);
    await page.getByRole('link', { name: 'Account', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out' }).click();
    await page.getByLabel('Email').fill(email);
    await page.getByLabel('Password', { exact: true }).fill(admin.password);
    const signedIn = page.waitForResponse(r => r.url().endsWith('/api/v1/accounts/login') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Sign in' }).click();
    const session = await signedIn;
    expect(session.status()).toBe(200);
    const restrictedHeaders = { Authorization: `Bearer ${(await session.json()).access_token}` };
    const me = await request.get('/api/v1/accounts/me', { headers: restrictedHeaders });
    expect(me.status()).toBe(200);
    expect((await me.json()).permissions).toMatchObject({ view: true, create: false, edit: false, export: false });
    await page.getByLabel('Search name or business owner').fill(name);
    await expect(page.getByRole('link', { name, exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'New application' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Export', exact: true })).toHaveCount(0);
    await page.getByRole('link', { name, exact: true }).click();
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
    for (const control of ['Record a review', 'Edit details', 'Change lifecycle', 'Assign reviewer']) await expect(page.getByRole('button', { name: control })).toHaveCount(0);
    const deniedReview = await request.post(`/api/v1/reviews/applications/${applicationId}`, { headers: restrictedHeaders, data: { date: '2000-01-01', health: 80, quality: 80, automation_coverage: 80, unit_test_coverage: 80, open_defects: 2, open_critical_defects: 1, risk: 'Low', note: '' } });
    expect(deniedReview.status()).toBe(403);
    expect((await deniedReview.json()).detail).toBe('Not permitted.');
    await page.getByRole('link', { name: 'Reports', exact: true }).click();
    await page.getByRole('button', { name: 'Open report' }).first().click();
    await expect(page.getByRole('row').filter({ hasText: name })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Export CSV' })).toHaveCount(0);
    const deniedExport = await request.get('/api/v1/reporting/applications/export', { headers: restrictedHeaders });
    expect(deniedExport.status()).toBe(403);
    expect(errors).toEqual([]);
  } finally {
    const restored = await request.put('/api/v1/admin/roles/engineer', { headers, data: { description: original.description, permissions: original.permissions } });
    const deactivated = userId ? await request.post(`/api/v1/admin/users/${userId}/deactivate`, { headers }) : null;
    const deletedApp = applicationId ? await request.delete(`/api/v1/applications/${applicationId}`, { headers }) : null;
    const deletedPortfolio = portfolioId ? await request.delete(`/api/v1/portfolios/${portfolioId}`, { headers }) : null;
    expect(restored.status(), 'restore engineer permissions').toBe(200);
    if (deactivated) expect(deactivated.status(), 'deactivate test user').toBe(200);
    if (deletedApp) expect(deletedApp.status(), 'delete test application').toBe(204);
    if (deletedPortfolio) expect(deletedPortfolio.status(), 'delete test portfolio').toBe(204);
  }
});
