import { expect, test } from '@playwright/test';

test('administrator creates, edits, searches, archives and deletes a portfolio', async ({ page }) => {
  const email = process.env.E2E_EMAIL;
  const password = process.env.E2E_NEW_PASSWORD;
  if (!email || !password) throw new Error('Set E2E_EMAIL and E2E_NEW_PASSWORD for an existing administrator.');
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const name = `Portfolio E2E ${Date.now()}`;
  await page.goto('/');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios' }).click();
  await page.getByRole('button', { name: 'New portfolio' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Owner', { exact: true }).fill('E2E Owner');
  await page.getByLabel('Product area', { exact: true }).fill('Finance');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Portfolio saved.')).toBeVisible();
  await page.getByLabel('Search name or owner').fill(name);
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible();
  await page.getByRole('button', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Owner', { exact: true }).fill('Updated owner');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Portfolio details' })).toContainText('Updated owner');
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Archive' }).click();
  await expect(page.getByText('Portfolio archived.')).toBeVisible();
  await page.getByLabel('Status', { exact: true }).selectOption('Archived');
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click();
  await expect(page.getByText('Portfolio deleted.')).toBeVisible();
  await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
